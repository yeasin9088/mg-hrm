-- Correct the original operator lookup after initial deployment; idempotent DDL.
CREATE OR REPLACE FUNCTION public.mghrm_sync_due_transfer_notifications()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $function$
DECLARE
  v_today date := (clock_timestamp() AT TIME ZONE 'Asia/Dhaka')::date;
  v_recipient uuid;
  v_recipients integer;
  v_cancelled integer := 0;
  v_created integer := 0;
  v_added integer;
  v_transfer record;
BEGIN
  -- Fail closed if the single-operator assumption no longer holds.
  SELECT count(*)::integer INTO v_recipients
    FROM public.profiles p JOIN auth.users u ON u.id = p.id
    WHERE p.is_active IS TRUE;
  IF v_recipients <> 1 THEN
    RETURN jsonb_build_object('status','Skipped','reason','Single active operator could not be resolved',
      'recipient_count',v_recipients,'created',0,'cancelled',0,'today',v_today);
  END IF;
  SELECT p.id INTO STRICT v_recipient
    FROM public.profiles p JOIN auth.users u ON u.id = p.id
    WHERE p.is_active IS TRUE;

  -- Future-dated reschedules must not keep a now-stale joining reminder active.
  -- Affect only reminders generated by THIS workflow (not legacy notifications).
  UPDATE public.notifications n
     SET status = 'Cancelled'
    FROM public.notification_events ev
    JOIN public.transfers t ON t.id::text = ev.entity_id
   WHERE n.event_id = ev.id
     AND ev.event_type = 'TransferJoiningConfirmationRequired'
     AND ev.event_key LIKE 'transfer:due:v1:%'
     AND n.entity_type = 'transfer'
     AND n.status IN ('Scheduled','Ready','Delivered','Read','Actioned','Snoozed','Failed')
     AND t.deleted_at IS NULL
     AND t.status IN ('Scheduled','Joining Pending')
     AND t.effective_date > v_today;
  GET DIAGNOSTICS v_cancelled = ROW_COUNT;

  FOR v_transfer IN
    SELECT t.id, t.employee_sys_id, t.effective_date
      FROM public.transfers t
      JOIN public.employees e ON e.id = t.employee_sys_id
     WHERE t.deleted_at IS NULL
       AND t.status IN ('Scheduled','Joining Pending')
       AND t.effective_date IS NOT NULL
       AND t.effective_date <= v_today
       AND e.deleted_at IS NULL
       AND lower(btrim(coalesce(e.status,''))) = 'active'
       AND NOT EXISTS (
         SELECT 1 FROM public.notification_events ne
          WHERE ne.event_key = 'transfer:due:v1:' || t.id::text || ':' || t.effective_date::text
       )
       -- Preserve a preexisting, user-dismissed bootstrap reminder rather than re-alert it.
       AND (t.rescheduled_at IS NOT NULL OR NOT EXISTS (
         SELECT 1 FROM public.notification_events ne
          WHERE ne.event_type = 'TransferJoiningConfirmationRequired'
            AND ne.entity_type = 'transfer'
            AND ne.entity_id = t.id::text
            AND ne.event_key LIKE 'bootstrap:%'
       ))
     ORDER BY t.effective_date, t.id
     LIMIT 100
  LOOP
    INSERT INTO public.notification_events
      (event_type,entity_type,entity_id,employee_sys_id,actor_user_id,
       event_key,event_payload,occurred_at)
    VALUES
      ('TransferJoiningConfirmationRequired','transfer',v_transfer.id::text,
       v_transfer.employee_sys_id,NULL,
       'transfer:due:v1:' || v_transfer.id::text || ':' || v_transfer.effective_date::text,
       jsonb_build_object(
         'recipient_user_id',v_recipient,
         'category','Transfer',
         'severity','Warning',
         'priority','High',
         'title','Transfer joining confirmation required',
         'message',format('Transfer order #%s is due for joining confirmation. Verify Joined or Not Joined.',v_transfer.id),
         'dedupe_key','transfer:due:v1:' || v_transfer.id::text || ':' || v_transfer.effective_date::text,
         'action_label','Review Transfer',
         'action_route','transfer',
         'action_params',jsonb_build_object('transfer_id',v_transfer.id),
         'scheduled_for',clock_timestamp()
       ),
       clock_timestamp())
    ON CONFLICT (event_key) DO NOTHING;
    GET DIAGNOSTICS v_added = ROW_COUNT;
    v_created := v_created + v_added;
  END LOOP;

  RETURN jsonb_build_object('status','Completed','today',v_today,
    'created',v_created,'cancelled',v_cancelled);
END;
$function$;

REVOKE ALL ON FUNCTION public.mghrm_sync_due_transfer_notifications() FROM PUBLIC, anon, authenticated;
COMMENT ON FUNCTION public.mghrm_sync_due_transfer_notifications() IS
'Cron-only idempotent Transfer joining-due event producer; never mutates employee assignments or transfer status.';
