import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import { PGlite } from '@electric-sql/pglite';

test('V1 unread suppression remains reversible and V2 repeat uses the source policy', async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
      CREATE SCHEMA notification_private;
      CREATE TABLE notification_private.governance_control(
        singleton boolean PRIMARY KEY, enabled boolean, allow_repeat boolean);
      INSERT INTO notification_private.governance_control VALUES(true,false,true);
      CREATE TABLE public.todos(id bigint PRIMARY KEY, assigned_to_user_id uuid,
        owner_user_id uuid);
      CREATE TABLE public.notification_events(id bigint PRIMARY KEY, event_type text);
      CREATE TABLE public.notification_escalation_rules(id bigint PRIMARY KEY,
        is_enabled boolean, repeat_every_minutes integer);
      CREATE TABLE public.notifications(
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        parent_notification_id bigint, repeat_count integer NOT NULL DEFAULT 0,
        escalation_level integer NOT NULL DEFAULT 0,
        recipient_user_id uuid, entity_type text, entity_id text,
        event_id bigint, status text, read_at timestamptz,
        escalation_rule_id bigint);
      CREATE FUNCTION public.notification_source_state(text,text)
        RETURNS jsonb LANGUAGE sql AS $$SELECT '{"supported":true,"resolved":false}'::jsonb$$;
      CREATE FUNCTION notification_private.governance_evaluate_todo(
        public.todos,uuid,timestamptz) RETURNS jsonb LANGUAGE sql AS $$
        SELECT jsonb_build_object('emit', allow_repeat)
        FROM notification_private.governance_control WHERE singleton
      $$;
      INSERT INTO public.todos VALUES
        (42,NULL,'11111111-1111-4111-8111-111111111111');
      INSERT INTO public.notification_events VALUES (1,'TodoReminderDue');
      INSERT INTO public.notification_escalation_rules VALUES (1,true,60);
      INSERT INTO public.notifications
        (id,recipient_user_id,entity_type,entity_id,event_id,status)
      VALUES (1,'11111111-1111-4111-8111-111111111111','todo','42',1,'Delivered');
    `);
    await db.exec(readFileSync(new URL('../supabase/migrations/20261023130000_governance_todo_repeat_gate.sql', import.meta.url), 'utf8'));
    await db.exec(`CREATE TRIGGER gate BEFORE INSERT ON public.notifications
      FOR EACH ROW EXECUTE FUNCTION notification_private.prevent_unseen_repeat()`);
    const insert = async () => (await db.query(`
      INSERT INTO public.notifications(parent_notification_id,repeat_count,
        escalation_level,recipient_user_id,entity_type,entity_id,event_id,
        status,escalation_rule_id)
      VALUES (1,1,0,'11111111-1111-4111-8111-111111111111','todo','42',1,
        'Ready',1) RETURNING id
    `)).rows.length;
    assert.equal(await insert(), 0, 'V1 unread root blocks repeat');
    await db.exec('UPDATE notification_private.governance_control SET enabled=true');
    assert.equal(await insert(), 1, 'V2 permits bounded repeat independently of read');
    await db.exec('UPDATE notification_private.governance_control SET allow_repeat=false');
    assert.equal(await insert(), 0, 'V2 evaluator suppresses repeat');
    await db.exec("UPDATE public.notifications SET status='Completed' WHERE id=1");
    await db.exec('UPDATE notification_private.governance_control SET allow_repeat=true');
    assert.equal(await insert(), 0, 'terminal root cannot repeat');
  } finally {
    await db.close();
  }
});
